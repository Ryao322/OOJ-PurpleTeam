    private void btnGenerateRecipesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerateRecipesActionPerformed
        // TODO add your handling code here:

        ArrayList<String> userAllergies = new ArrayList<>();

        boolean currentUserFound = false;

// STEP 1: Read the user's saved allergies
        try (BufferedReader allergyReader
                = new BufferedReader(new FileReader("allergies.txt"))) {

            String allergyLine;

            while ((allergyLine = allergyReader.readLine()) != null) {

                if (allergyLine.startsWith("Name:")) {
                    String savedName = allergyLine.substring(5).trim();

                    currentUserFound
                            = savedName.equalsIgnoreCase(fullName.trim());
                }

                if (currentUserFound && allergyLine.startsWith("Allergies:")) {

                    String allergyText = allergyLine.substring(10).trim();

                    if (!allergyText.isEmpty()) {
                        for (String allergy : allergyText.split(",")) {
                            userAllergies.add(allergy.trim().toLowerCase());
                        }
                    }

                    break;
                }
            }

        } catch (IOException e) {
            JOptionPane.showMessageDialog(this,
                    "Error reading allergies: " + e.getMessage());
            return;
        }

// STEP 2: Check whether a profile exists
        if (!currentUserFound) {
            JOptionPane.showMessageDialog(this,
                    "No saved allergy profile found.");
            return;
        }

// STEP 3: Read recipes and filter allergens
        StringBuilder results = new StringBuilder();

        try (BufferedReader reader
                = new BufferedReader(new FileReader("recipes.txt"))) {

            String line;

            while ((line = reader.readLine()) != null) {

                String[] recipeDetails = line.split("\\|", -1);

                if (recipeDetails.length >= 4) {

                    String recipeName = recipeDetails[0].trim();
                    String category = recipeDetails[1].trim();
                    String ingredients = recipeDetails[2].trim();
                    String instructions = recipeDetails[3].trim();

                    boolean hasAllergen = false;

                    for (String allergy : userAllergies) {

                        if (!allergy.isEmpty()
                                && ingredients.toLowerCase().contains(allergy)) {
                            hasAllergen = true;
                            break;
                        }
                    }

                    // Display only recipes without matching allergens
                    if (!hasAllergen) {

                        results.append("RECIPE: ")
                                .append(recipeName).append("\n");

                        results.append("Category: ")
                                .append(category).append("\n");

                        results.append("Ingredients: ")
                                .append(ingredients).append("\n");

                        results.append("Instructions: ")
                                .append(instructions).append("\n");

                        results.append("--------------------------------\n\n");
                    }
                }
            }

        } catch (IOException e) {

            JOptionPane.showMessageDialog(this,
                    "Error reading recipes: " + e.getMessage());
            return;
        }

// STEP 4: Display suitable recipes
        if (results.length() == 0) {

            txtRecipeResults.setText(
                    "No safe recipes found for your allergy profile.");

        } else {

            txtRecipeResults.setText(results.toString());
        }

    }//GEN-LAST:event_btnGenerateRecipesActionPerformed

